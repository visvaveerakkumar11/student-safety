-- =====================================================================
-- Child Safety Verification System for School Transport
-- PostgreSQL schema (run in the Supabase SQL Editor, then run seed.sql)
-- =====================================================================
-- WARNING: this script DROPS and recreates all application tables.
-- Run it only against the database dedicated to this project.
-- =====================================================================

drop table if exists notifications   cascade;
drop table if exists scan_events     cascade;
drop table if exists bus_assignments cascade;
drop table if exists rfid_cards      cascade;
drop table if exists students        cascade;
drop table if exists buses           cascade;
drop table if exists admins          cascade;

-- ---------------------------------------------------------------------
-- Admin accounts (passwords are BCrypt hashes; the first admin is
-- bootstrapped by the backend from ADMIN_EMAIL / ADMIN_PASSWORD).
-- ---------------------------------------------------------------------
create table admins (
    id             bigint generated by default as identity primary key,
    email          text        not null unique check (email = lower(email)),
    full_name      text        not null,
    password_hash  text        not null,
    created_at     timestamptz not null default now(),
    last_login_at  timestamptz
);

-- ---------------------------------------------------------------------
-- Buses
-- ---------------------------------------------------------------------
create table buses (
    id                  bigint generated by default as identity primary key,
    bus_number          text        not null unique,
    registration_number text        not null unique,
    driver_name         text        not null,
    driver_phone        text        not null,
    route_name          text        not null,
    capacity            integer     not null check (capacity between 1 and 100),
    status              text        not null default 'ACTIVE'
                        check (status in ('ACTIVE', 'INACTIVE', 'MAINTENANCE')),
    created_at          timestamptz not null default now(),
    updated_at          timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- Students (current transport state lives here; history is in scan_events)
-- ---------------------------------------------------------------------
create table students (
    id                bigint generated by default as identity primary key,
    admission_number  text        not null unique,
    full_name         text        not null,
    class_name        text        not null,
    section           text        not null,
    parent_name       text        not null,
    parent_phone      text        not null,
    transport_status  text        not null default 'NOT_BOARDED'
                      check (transport_status in ('NOT_BOARDED', 'ONBOARD', 'EXITED')),
    last_scan_at      timestamptz,
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now()
);

create index idx_students_class on students (class_name, section);
create index idx_students_status on students (transport_status);

-- ---------------------------------------------------------------------
-- RFID cards. UIDs are stored canonical: uppercase hex, no separators.
-- A card can be released from a student (student_id = null, INACTIVE).
-- ---------------------------------------------------------------------
create table rfid_cards (
    id          bigint generated by default as identity primary key,
    uid         text        not null unique check (uid ~ '^[0-9A-F]{4,32}$'),
    student_id  bigint      unique references students (id) on delete set null,
    status      text        not null default 'ACTIVE' check (status in ('ACTIVE', 'INACTIVE')),
    issued_at   timestamptz not null default now(),
    updated_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- Current bus assignment (one bus per student).
-- ---------------------------------------------------------------------
create table bus_assignments (
    id           bigint generated by default as identity primary key,
    student_id   bigint      not null unique references students (id) on delete cascade,
    bus_id       bigint      not null references buses (id) on delete cascade,
    assigned_at  timestamptz not null default now()
);

create index idx_bus_assignments_bus on bus_assignments (bus_id);

-- ---------------------------------------------------------------------
-- Every RFID scan, accepted or rejected. Student / bus references are
-- nulled (not deleted) when the student or bus is removed; the name and
-- number snapshots keep the history readable.
-- ---------------------------------------------------------------------
create table scan_events (
    id                bigint generated by default as identity primary key,
    rfid_uid          text        not null,
    student_id        bigint      references students (id) on delete set null,
    bus_id            bigint      references buses (id) on delete set null,
    student_name      text,
    bus_number        text,
    event_type        text        check (event_type in ('BOARDING', 'EXIT')),
    result            text        not null check (result in ('ACCEPTED', 'REJECTED')),
    rejection_reason  text        check (rejection_reason in (
                          'BUS_NOT_FOUND', 'BUS_NOT_ACTIVE', 'UNKNOWN_CARD', 'CARD_INACTIVE',
                          'STUDENT_NOT_ASSIGNED', 'UNAUTHORIZED_BUS', 'DUPLICATE_SCAN',
                          'ALREADY_ONBOARD', 'NOT_ONBOARD', 'BUS_FULL')),
    message           text        not null,
    source            text        not null default 'SIMULATOR' check (source in ('SIMULATOR', 'READER')),
    scanned_at        timestamptz not null default now(),
    check ((result = 'ACCEPTED') = (rejection_reason is null))
);

create index idx_scan_events_scanned_at on scan_events (scanned_at desc);
create index idx_scan_events_student on scan_events (student_id, scanned_at desc);
create index idx_scan_events_bus on scan_events (bus_id, scanned_at desc);
create index idx_scan_events_result on scan_events (result, scanned_at desc);

-- ---------------------------------------------------------------------
-- Parent notifications (full history; one per accepted scan).
-- ---------------------------------------------------------------------
create table notifications (
    id                   bigint generated by default as identity primary key,
    scan_event_id        bigint      references scan_events (id) on delete set null,
    student_id           bigint      references students (id) on delete set null,
    student_name         text        not null,
    bus_number           text        not null,
    recipient_name       text        not null,
    recipient_phone      text        not null,
    event_type           text        not null check (event_type in ('BOARDING', 'EXIT')),
    message              text        not null,
    status               text        not null default 'PENDING'
                         check (status in ('PENDING', 'SENT', 'DELIVERED', 'FAILED')),
    provider             text        not null,
    simulated            boolean     not null,
    provider_message_id  text,
    failure_reason       text,
    attempts             integer     not null default 0,
    created_at           timestamptz not null default now(),
    sent_at              timestamptz,
    delivered_at         timestamptz,
    updated_at           timestamptz not null default now()
);

create index idx_notifications_created_at on notifications (created_at desc);
create index idx_notifications_status on notifications (status, created_at desc);
create index idx_notifications_student on notifications (student_id);
create index idx_notifications_scan_event on notifications (scan_event_id);

-- ---------------------------------------------------------------------
-- Security: these tables hold children's data and are accessed only by
-- the Spring Boot backend (table owner, bypasses RLS). Enabling RLS with
-- no policies blocks the Supabase anon/authenticated REST API entirely.
-- ---------------------------------------------------------------------
alter table admins          enable row level security;
alter table buses           enable row level security;
alter table students        enable row level security;
alter table rfid_cards      enable row level security;
alter table bus_assignments enable row level security;
alter table scan_events     enable row level security;
alter table notifications   enable row level security;
